using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Xml;
using System.Xml.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Nexer.Xaml.Generators;

/// <summary>
/// Generates, for every XAML file (an <c>AdditionalFiles</c> item ending in <c>.xaml</c>) with an <c>x:Class</c>, a
/// partial class with a typed field per <c>x:Name</c> and an <c>InitializeComponent()</c> method that loads the
/// compiled XAML through <c>Nexer.Ui.Markup.XamlComponent</c> and assigns the fields.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class XamlCodeBehindGenerator : IIncrementalGenerator
{
    private const string XamlLanguageNamespace2006 = "http://schemas.microsoft.com/winfx/2006/xaml";
    private const string XamlLanguageNamespace2009 = "http://schemas.microsoft.com/winfx/2009/xaml";
    private const string XmlnsDefinitionAttributeName = "XmlnsDefinitionAttribute";
    private const string DeferredContentAttributeName = "DeferredContentAttribute";

    private static readonly DiagnosticDescriptor s_classNotFound = new(
        "NXAMLG001", "x:Class type not found",
        "x:Class '{0}' in '{1}' does not match a class declared in this project; no InitializeComponent was generated",
        "Nexer.Xaml", DiagnosticSeverity.Warning, true);

    private static readonly DiagnosticDescriptor s_notPartial = new(
        "NXAMLG002", "x:Class type is not partial",
        "Declare '{0}' (and its containing types) as partial to get a generated InitializeComponent and x:Name fields",
        "Nexer.Xaml", DiagnosticSeverity.Warning, true);

    private static readonly DiagnosticDescriptor s_nameSkipped = new(
        "NXAMLG003", "x:Name field not generated",
        "No field was generated for x:Name '{0}' in '{1}': {2}",
        "Nexer.Xaml", DiagnosticSeverity.Warning, true);

    private static readonly DiagnosticDescriptor s_duplicateClass = new(
        "NXAMLG004", "Duplicate x:Class",
        "x:Class '{0}' is used by more than one XAML file; code was generated for '{1}' only",
        "Nexer.Xaml", DiagnosticSeverity.Warning, true);

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var documents = context.AdditionalTextsProvider
            .Where(static text => text.Path.EndsWith(".xaml", StringComparison.OrdinalIgnoreCase))
            .Select(static (text, cancellationToken) => XamlDocumentModel.Parse(text.Path, text.GetText(cancellationToken)?.ToString()))
            .Where(static model => model is not null)
            .Collect();

        context.RegisterSourceOutput(documents.Combine(context.CompilationProvider), static (spc, input) => Execute(spc, input.Left!, input.Right));
    }

    private static void Execute(SourceProductionContext context, ImmutableArray<XamlDocumentModel?> documents, Compilation compilation)
    {
        if (documents.IsDefaultOrEmpty)
        {
            return;
        }

        var xmlns = XmlnsMap.Create(compilation);
        var generated = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var document in documents.OrderBy(d => d!.Path, StringComparer.Ordinal))
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            var model = document!;
            if (generated.TryGetValue(model.ClassName, out var firstPath))
            {
                context.ReportDiagnostic(Diagnostic.Create(s_duplicateClass, Location.None, model.ClassName, firstPath));
                continue;
            }

            var classSymbol = compilation.Assembly.GetTypeByMetadataName(model.ClassName);
            if (classSymbol is null || classSymbol.DeclaringSyntaxReferences.Length == 0)
            {
                context.ReportDiagnostic(Diagnostic.Create(s_classNotFound, Location.None, model.ClassName, model.Path));
                continue;
            }

            if (!IsPartialChain(classSymbol))
            {
                context.ReportDiagnostic(Diagnostic.Create(s_notPartial, classSymbol.Locations.FirstOrDefault(), classSymbol.ToDisplayString()));
                continue;
            }

            generated.Add(model.ClassName, model.Path);
            var source = GenerateSource(context, compilation, xmlns, model, classSymbol);
            context.AddSource(HintName(model.ClassName), SourceText.From(source, Encoding.UTF8));
        }
    }

    private static string GenerateSource(SourceProductionContext context, Compilation compilation, XmlnsMap xmlns, XamlDocumentModel model, INamedTypeSymbol classSymbol)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated>Generated by Nexer.Xaml.Generators from " + EscapeComment(model.Path) + "</auto-generated>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        var ns = classSymbol.ContainingNamespace;
        var indent = string.Empty;
        if (ns is { IsGlobalNamespace: false })
        {
            builder.Append("namespace ").AppendLine(ns.ToDisplayString());
            builder.AppendLine("{");
            indent = "    ";
        }

        var chain = new List<INamedTypeSymbol>();
        for (var type = classSymbol; type is not null; type = type.ContainingType)
        {
            chain.Insert(0, type);
        }

        foreach (var type in chain)
        {
            builder.Append(indent).Append("partial ").Append(TypeKeyword(type)).Append(' ').Append(type.Name);
            if (type.TypeParameters.Length > 0)
            {
                builder.Append('<').Append(string.Join(", ", type.TypeParameters.Select(p => p.Name))).Append('>');
            }

            builder.AppendLine();
            builder.Append(indent).AppendLine("{");
            indent += "    ";
        }

        var existingMembers = new HashSet<string>(StringComparer.Ordinal);
        for (var type = classSymbol; type is not null; type = type.BaseType)
        {
            foreach (var name in type.MemberNames)
            {
                existingMembers.Add(name);
            }
        }

        var fields = new List<(string Name, string Type)>();
        foreach (var element in model.Names)
        {
            if (!SyntaxFacts.IsValidIdentifier(element.Name))
            {
                context.ReportDiagnostic(Diagnostic.Create(s_nameSkipped, Location.None, element.Name, model.Path, "it is not a valid C# identifier"));
                continue;
            }

            if (existingMembers.Contains(element.Name) || element.Name == "InitializeComponent" || fields.Any(f => f.Name == element.Name))
            {
                context.ReportDiagnostic(Diagnostic.Create(s_nameSkipped, Location.None, element.Name, model.Path,
                    "a member with that name already exists"));
                continue;
            }

            var resolved = xmlns.Resolve(compilation, element.XmlNamespace, element.LocalName);
            if (resolved is not null && !compilation.IsSymbolAccessibleWithin(resolved, classSymbol))
            {
                resolved = null;
            }

            if (resolved is not null && xmlns.IsInDeferredContent(compilation, element.PropertyPath))
            {
                // Elements in deferred content (templates) are created later, possibly many times.
                continue;
            }

            var typeName = resolved?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) ?? "object";
            fields.Add((element.Name, typeName));
            var name = SyntaxFacts.GetKeywordKind(element.Name) != SyntaxKind.None ? "@" + element.Name : element.Name;
            builder.Append(indent).Append("/// <summary>The element named <c>").Append(element.Name).AppendLine("</c> in the XAML.</summary>");
            builder.Append(indent).Append("[global::System.CodeDom.Compiler.GeneratedCode(\"Nexer.Xaml.Generators\", \"1.0\")]").AppendLine();
            builder.Append(indent).Append(FieldModifier(element.FieldModifier)).Append(' ').Append(typeName).Append(' ').Append(name)
                .AppendLine(" = default!;");
            builder.AppendLine();
        }

        if (classSymbol.GetMembers("InitializeComponent").IsEmpty)
        {
            var self = classSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            builder.Append(indent).AppendLine("/// <summary>Loads the compiled XAML into this instance and assigns the x:Name fields.</summary>");
            builder.Append(indent).AppendLine("/// <param name=\"services\">Optional services available to markup extensions.</param>");
            builder.Append(indent).Append("[global::System.CodeDom.Compiler.GeneratedCode(\"Nexer.Xaml.Generators\", \"1.0\")]").AppendLine();
            builder.Append(indent).AppendLine("private void InitializeComponent(global::System.IServiceProvider? services = null)");
            builder.Append(indent).AppendLine("{");
            builder.Append(indent).Append("    global::Nexer.Ui.Markup.XamlComponent.InitializeComponent<").Append(self).AppendLine(">(this, services);");
            foreach (var (name, type) in fields)
            {
                var member = SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;
                builder.Append(indent).Append("    this.").Append(member).Append(" = (").Append(type)
                    .Append(")global::Nexer.Ui.Markup.NameScope.FindName(this, \"").Append(name).AppendLine("\")!;");
            }

            builder.Append(indent).AppendLine("}");
        }

        for (var i = 0; i < chain.Count; i++)
        {
            indent = indent.Substring(4);
            builder.Append(indent).AppendLine("}");
        }

        if (ns is { IsGlobalNamespace: false })
        {
            builder.AppendLine("}");
        }

        return builder.ToString();
    }

    private static bool IsPartialChain(INamedTypeSymbol type)
    {
        for (var current = type; current is not null; current = current.ContainingType)
        {
            var isPartial = current.DeclaringSyntaxReferences
                .Select(r => r.GetSyntax())
                .OfType<Microsoft.CodeAnalysis.CSharp.Syntax.TypeDeclarationSyntax>()
                .Any(d => d.Modifiers.Any(m => m.IsKind(SyntaxKind.PartialKeyword)));
            if (!isPartial)
            {
                return false;
            }
        }

        return true;
    }

    private static string TypeKeyword(INamedTypeSymbol type) => type switch
    {
        { IsRecord: true, TypeKind: TypeKind.Struct } => "record struct",
        { IsRecord: true } => "record",
        { TypeKind: TypeKind.Struct } => "struct",
        { TypeKind: TypeKind.Interface } => "interface",
        _ => "class",
    };

    private static string FieldModifier(string? modifier) => modifier?.Trim().ToLowerInvariant() switch
    {
        "public" => "public",
        "private" => "private",
        "protected" => "protected",
        "protected internal" => "protected internal",
        "private protected" => "private protected",
        "friend" => "internal",
        _ => "internal",
    };

    private static string HintName(string className)
    {
        var builder = new StringBuilder();
        foreach (var c in className)
        {
            builder.Append(char.IsLetterOrDigit(c) || c == '.' ? c : '_');
        }

        return builder.Append(".xaml.g.cs").ToString();
    }

    private static string EscapeComment(string text) => text.Replace("\r", " ").Replace("\n", " ").Replace("<", "&lt;").Replace(">", "&gt;");

    private sealed class XmlnsMap
    {
        private readonly Dictionary<string, List<(IAssemblySymbol Assembly, string ClrNamespace)>> _map = new(StringComparer.Ordinal);

        public static XmlnsMap Create(Compilation compilation)
        {
            var map = new XmlnsMap();
            foreach (var assembly in new[] { compilation.Assembly }.Concat(compilation.SourceModule.ReferencedAssemblySymbols))
            {
                foreach (var attribute in assembly.GetAttributes())
                {
                    if (attribute.AttributeClass?.Name == XmlnsDefinitionAttributeName
                        && attribute.ConstructorArguments.Length == 2
                        && attribute.ConstructorArguments[0].Value is string xmlNamespace
                        && attribute.ConstructorArguments[1].Value is string clrNamespace)
                    {
                        if (!map._map.TryGetValue(xmlNamespace, out var list))
                        {
                            map._map[xmlNamespace] = list = [];
                        }

                        list.Add((assembly, clrNamespace));
                    }
                }
            }

            return map;
        }

        public INamedTypeSymbol? Resolve(Compilation compilation, string xmlNamespace, string localName)
        {
            foreach (var name in new[] { localName, localName + "Extension" })
            {
                var type = ResolveExact(compilation, xmlNamespace, name);
                if (type is not null)
                {
                    return type;
                }
            }

            return null;
        }

        // propertyPath: the chain of (xmlNamespace, "Owner.Property") property elements enclosing the element.
        public bool IsInDeferredContent(Compilation compilation, EquatableArray<PropertyElement> propertyPath)
        {
            foreach (var property in propertyPath)
            {
                var dot = property.LocalName.IndexOf('.');
                var owner = Resolve(compilation, property.XmlNamespace, property.LocalName.Substring(0, dot));
                var propertyName = property.LocalName.Substring(dot + 1);
                for (var type = owner; type is not null; type = type.BaseType)
                {
                    var symbol = type.GetMembers(propertyName).OfType<IPropertySymbol>().FirstOrDefault();
                    if (symbol is not null)
                    {
                        if (symbol.GetAttributes().Any(a => a.AttributeClass?.Name == DeferredContentAttributeName))
                        {
                            return true;
                        }

                        break;
                    }
                }
            }

            return false;
        }

        private INamedTypeSymbol? ResolveExact(Compilation compilation, string xmlNamespace, string localName)
        {
            if (TryParseClrNamespace(xmlNamespace, out var clrNamespace, out var assemblyName))
            {
                var metadataName = clrNamespace + "." + localName;
                if (assemblyName is null)
                {
                    return compilation.Assembly.GetTypeByMetadataName(metadataName) ?? compilation.GetTypeByMetadataName(metadataName);
                }

                var assembly = new[] { compilation.Assembly }.Concat(compilation.SourceModule.ReferencedAssemblySymbols)
                    .FirstOrDefault(a => a.Name == assemblyName);
                return assembly?.GetTypeByMetadataName(metadataName);
            }

            if (_map.TryGetValue(xmlNamespace, out var list))
            {
                foreach (var (assembly, ns) in list)
                {
                    var type = assembly.GetTypeByMetadataName(ns + "." + localName);
                    if (type is not null)
                    {
                        return type;
                    }
                }
            }

            return null;
        }

        private static bool TryParseClrNamespace(string xmlNamespace, out string clrNamespace, out string? assemblyName)
        {
            assemblyName = null;
            if (xmlNamespace.StartsWith("using:", StringComparison.Ordinal))
            {
                clrNamespace = xmlNamespace.Substring("using:".Length).Trim();
                return true;
            }

            if (xmlNamespace.StartsWith("clr-namespace:", StringComparison.Ordinal))
            {
                var parts = xmlNamespace.Substring("clr-namespace:".Length).Split(';');
                clrNamespace = parts[0].Trim();
                foreach (var part in parts.Skip(1))
                {
                    var trimmed = part.Trim();
                    if (trimmed.StartsWith("assembly=", StringComparison.Ordinal))
                    {
                        assemblyName = trimmed.Substring("assembly=".Length).Trim();
                    }
                }

                return true;
            }

            clrNamespace = string.Empty;
            return false;
        }
    }

    /// <summary>The parts of a XAML document the generator needs (equatable, so unchanged files are cached).</summary>
    private sealed record XamlDocumentModel(string Path, string ClassName, EquatableArray<NamedElement> Names)
    {
        public static XamlDocumentModel? Parse(string path, string? text)
        {
            if (string.IsNullOrWhiteSpace(text))
            {
                return null;
            }

            XDocument document;
            try
            {
                document = XDocument.Parse(text, LoadOptions.None);
            }
            catch (XmlException)
            {
                return null; // The build step reports XML errors.
            }

            var root = document.Root;
            var className = root is null ? null : XamlAttribute(root, "Class");
            if (root is null || string.IsNullOrWhiteSpace(className))
            {
                return null;
            }

            var names = new List<NamedElement>();
            Collect(root, [], names);
            return new XamlDocumentModel(path, className!.Trim(), new EquatableArray<NamedElement>([.. names]));
        }

        private static void Collect(XElement element, ImmutableArray<PropertyElement> propertyPath, List<NamedElement> names)
        {
            var isPropertyElement = element.Name.LocalName.IndexOf('.') >= 0;
            if (!isPropertyElement)
            {
                var name = XamlAttribute(element, "Name") ?? element.Attribute("Name")?.Value;
                if (!string.IsNullOrWhiteSpace(name) && element.Parent is not null)
                {
                    names.Add(new NamedElement(name!.Trim(), element.Name.NamespaceName, element.Name.LocalName,
                        XamlAttribute(element, "FieldModifier"), new EquatableArray<PropertyElement>(propertyPath)));
                }
            }

            var childPath = isPropertyElement
                ? propertyPath.Add(new PropertyElement(element.Name.NamespaceName, element.Name.LocalName))
                : propertyPath;
            foreach (var child in element.Elements())
            {
                Collect(child, childPath, names);
            }
        }

        private static string? XamlAttribute(XElement element, string name) =>
            element.Attribute(XName.Get(name, XamlLanguageNamespace2006))?.Value
            ?? element.Attribute(XName.Get(name, XamlLanguageNamespace2009))?.Value;
    }

    private sealed record NamedElement(string Name, string XmlNamespace, string LocalName, string? FieldModifier, EquatableArray<PropertyElement> PropertyPath);

    private sealed record PropertyElement(string XmlNamespace, string LocalName);
}
