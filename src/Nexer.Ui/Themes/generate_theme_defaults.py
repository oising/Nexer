"""Generates ColorTheme.Defaults.g.cs from Jexer's bits/ColorTheme.java (setDefaultTheme).

Usage: python generate_theme_defaults.py <path-to-jexer>/src/jexer/bits/ColorTheme.java
Jexer is MIT licensed, (c) Autumn Lamonte.
"""
import os
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
body = src[src.index("public void setDefaultTheme()"):]
body = body[:body.index("public void setFemme()")]

entries = []
cur = None
for line in body.splitlines():
    line = line.strip()
    if line.startswith("color = new CellAttributes()"):
        cur = {"fg": "white", "bg": "black", "bold": False}
    elif m := re.match(r"color\.setForeColor\(Color\.(\w+)\);", line):
        cur["fg"] = m.group(1).lower()
    elif m := re.match(r"color\.setBackColor\(Color\.(\w+)\);", line):
        cur["bg"] = m.group(1).lower()
    elif m := re.match(r"color\.setForeColorRGB\(0x([0-9A-Fa-f]+)\);", line):
        cur["fg"] = "#" + m.group(1).upper().rjust(6, "0")
    elif m := re.match(r"color\.setBackColorRGB\(0x([0-9A-Fa-f]+)\);", line):
        cur["bg"] = "#" + m.group(1).upper().rjust(6, "0")
    elif m := re.match(r"color\.setBold\((true|false)\);", line):
        cur["bold"] = m.group(1) == "true"
    elif m := re.match(r'colors\.put\("([^"]+)", color\);', line):
        spec = ("bold " if cur["bold"] else "") + f'{cur["fg"]} on {cur["bg"]}'
        entries.append((m.group(1), spec))

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ColorTheme.Defaults.g.cs")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// <auto-generated>\n")
    f.write("// Generated by generate_theme_defaults.py from Jexer bits/ColorTheme.java setDefaultTheme().\n")
    f.write("// Ported from Jexer bits/ColorTheme.java (MIT, \u00a9 Autumn Lamonte).\n")
    f.write("// </auto-generated>\n\n")
    f.write("namespace Nexer.Ui;\n\n")
    f.write("public partial class ColorTheme\n{\n")
    f.write("    /// <summary>Jexer's default theme as (key, <see cref=\"StyleSyntax\"/> text) pairs.</summary>\n")
    f.write("    public static IReadOnlyList<KeyValuePair<string, string>> DefaultColorSpecs { get; } =\n    [\n")
    for k, v in entries:
        f.write(f'        new("{k}", "{v}"),\n')
    f.write("    ];\n}\n")
print(f"{len(entries)} entries")
