"""Regenerate the pinned Unicode tables and official grapheme conformance fixture."""

from pathlib import Path
import hashlib
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
VERSION = "17.0.0"
BASE = f"https://www.unicode.org/Public/{VERSION}/ucd/"
GCB = {
    "CR": 1, "LF": 2, "Control": 3, "Extend": 4, "ZWJ": 5,
    "Regional_Indicator": 6, "Prepend": 7, "SpacingMark": 8,
    "L": 9, "V": 10, "T": 11, "LV": 12, "LVT": 13,
}
HASHES = {
    "auxiliary/GraphemeBreakProperty.txt": "d6b51d1d2ae5c33b451b7ed994b48f1f4dc62b2272a5831e7fd418514a6bae89",
    "DerivedCoreProperties.txt": "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08",
    "EastAsianWidth.txt": "ea7ce50f3444a050333448dffef1cadd9325af55cbb764b4a2280faf52170a33",
    "emoji/emoji-data.txt": "2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b",
    "auxiliary/GraphemeBreakTest.txt": "e2d134d2c52919bace503ebb6a551c1855fe1a1faec18478c78fff254a1793ec",
}


def fetch(path):
    with urllib.request.urlopen(BASE + path, timeout=60) as response:
        content = response.read()
    digest = hashlib.sha256(content).hexdigest()
    if digest != HASHES[path]:
        raise ValueError(f"Unexpected Unicode source digest: {path}: {digest}")
    print(f"{path}: {digest}")
    return content.decode("utf-8-sig")


def ranges(text, select):
    result = []
    for line in text.splitlines():
        fields = [field.strip() for field in line.split("#")[0].split(";")]
        if len(fields) < 2:
            continue
        value = select(fields[1:])
        if not value:
            continue
        ends = fields[0].split("..")
        result.append((int(ends[0], 16), int(ends[-1], 16), value))
    result.sort()
    merged = []
    for start, end, value in result:
        if merged and merged[-1][1] + 1 == start and merged[-1][2] == value:
            merged[-1] = (merged[-1][0], end, value)
        else:
            merged.append((start, end, value))
    return merged


graphemes = fetch("auxiliary/GraphemeBreakProperty.txt")
derived = fetch("DerivedCoreProperties.txt")
widths = fetch("EastAsianWidth.txt")
emoji = fetch("emoji/emoji-data.txt")
tables = {
    "Grapheme": ranges(graphemes, lambda f: GCB.get(f[0], 0)),
    "Conjunct": ranges(derived, lambda f: {"Consonant": 1, "Extend": 2, "Linker": 3}.get(f[1], 0)
                      if f[0] == "InCB" else 0),
    "EastAsian": ranges(widths, lambda f: {"W": 1, "F": 1, "A": 2}.get(f[0], 0)),
    "Pictographic": ranges(emoji, lambda f: int(f[0] == "Extended_Pictographic")),
    "EmojiPresentation": ranges(emoji, lambda f: int(f[0] == "Emoji_Presentation")),
}
lines = [
    "// Generated by tools/generate_unicode.py. Do not edit.",
    "// Unicode 17.0.0 data. See THIRD-PARTY-NOTICES.txt and LICENSE-Unicode.txt.",
    "namespace Nexer.Core.Text;",
    "",
    "internal static class UnicodeData",
    "{",
]
for name, entries in tables.items():
    lines += [f"    internal static ReadOnlySpan<int> {name} =>", "    ["]
    lines += [f"        0x{start:X}, 0x{end:X}, {value}," for start, end, value in entries]
    lines += ["    ];", ""]
lines += ["}", ""]
destination = ROOT / "src" / "Nexer.Core" / "Text" / "UnicodeData.g.cs"
destination.parent.mkdir(parents=True, exist_ok=True)
destination.write_text("\n".join(lines), encoding="utf-8")
fixture = ROOT / "tests" / "Nexer.Core.Tests" / "TestData" / "GraphemeBreakTest-17.0.0.txt"
fixture.parent.mkdir(parents=True, exist_ok=True)
fixture.write_text(fetch("auxiliary/GraphemeBreakTest.txt"), encoding="utf-8")
with urllib.request.urlopen("https://www.unicode.org/license.txt", timeout=60) as response:
    (ROOT / "LICENSE-Unicode.txt").write_bytes(response.read())
